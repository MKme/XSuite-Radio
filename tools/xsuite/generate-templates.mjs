// Run the application's existing encoders. Firmware only fills the generated dynamic slots.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
let xtocWeb = process.env.XTOC_WEB_ROOT;
let check = false;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--check') check = true;
  else if (args[i] === '--xtoc-web' && args[i + 1] && !args[i + 1].startsWith('--')) xtocWeb = args[++i];
  else if (args[i] === '--help') {
    console.log('Usage: node tools/xsuite/generate-templates.mjs [--check] [--xtoc-web PATH]\n' +
      'Use the existing XTOC xtoc-web source and installed build dependencies. XTOC_WEB_ROOT also selects it.');
    process.exit(0);
  } else throw Error('Unknown or incomplete option: ' + args[i]);
}
const app = path.resolve(xtocWeb || path.join(root, '../../xtoc-web'));
const entry = path.join(app, 'src/core/packet.ts');
try {
  await readFile(path.join(app, 'package.json'));
  await readFile(entry);
} catch {
  throw Error('Canonical XTOC source is required. Set --xtoc-web PATH (the xtoc-web directory) or XTOC_WEB_ROOT; generated firmware templates remain unchanged.');
}
const require = createRequire(path.join(app, 'package.json'));
const { build } = require('esbuild');
const compiled = await build({ entryPoints: [entry], bundle: true, write: false, format: 'esm', platform: 'node' });
const p = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const minutes = 0x01020304;
const base = { src: 65535, dst: 0, t: minutes * 60000, pri: 3 };
const actions = [
  ['CHECKIN', 'Check in / OK', 4, v => p.encodeCheckinLocClear({ unitId: 65535, status: 0, ...v }), true],
  ['SOS', 'SOS - send', 9, v => p.encodeEventClear({ ...base, status: 1, typeCode: 255, label: 'SOS', pri: 0, ...v })],
  ['MEDICAL', 'Need medical help', 9, v => p.encodeEventClear({ ...base, status: 1, typeCode: 254, label: 'MEDICAL', pri: 0, ...v })],
  ['HELP', 'Need assistance', 1, v => p.encodeSitrepClear({ ...base, status: 1, note: 'Need assistance', pri: 0, ...v })],
  ['RTB', 'Returning to base', 4, v => p.encodeCheckinLocClear({ unitId: 65535, status: 2, ...v }), true],
  ['ARRIVED', 'Arrived', 1, v => p.encodeSitrepClear({ ...base, status: 0, note: 'Arrived', ...v })],
  ['ALL_CLEAR', 'All clear - send', 9, v => p.encodeEventClear({ ...base, status: 2, typeCode: 255, label: 'SOS', note: 'ALL CLEAR', pri: 0, ...v })],
  ['SITREP', 'Status report', 1, v => p.encodeSitrepClear({ ...base, status: 0, note: 'Status report', ...v })],
  ['CONTACT', 'Report observation', 2, v => p.encodeContactClear({ ...base, typeCode: 0, count: 1, dir: 255, note: 'Observation', ...v })],
  ...['Water', 'Food', 'Fuel', 'Medical supplies', 'Transport', 'Equipment'].map((s, i) => [
    'RESOURCE_' + i, 'Request ' + s.toLowerCase(), 5,
    v => p.encodeResourceClear({ ...base, itemCode: 0, qty: 1, note: s + ' requested', ...v }),
  ]),
  ['TASK_ACK', 'Task acknowledged', 3, v => p.encodeTaskClear({ ...base, actionCode: 0, dueMins: 0, note: 'Task acknowledged', ...v })],
  ['TASK_DONE', 'Task completed', 3, v => p.encodeTaskClear({ ...base, actionCode: 0, dueMins: 0, note: 'Task completed', ...v })],
  ['MESSAGE', 'Reply: received', 13, v => p.encodeMessageClear({ ...base, prec: 'R', msgType: 0, text: 'Received', ...v, prec: 'ZOPR'[v.pri ?? 3] })],
  ['HAZARD', 'Report hazard', 9, v => p.encodeEventClear({ ...base, status: 1, typeCode: 0, label: 'HAZARD', pri: 1, ...v })],
];
const be = n => { const b = Buffer.alloc(4); b.writeInt32BE(n); return b; };
let header = '// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 The RadioFoundry Authors\n// Copyright (c) 2026 MKME Media\n';
header += '// Generated by tools/xsuite/generate-templates.mjs from the existing XTOC packet encoders.\n';
header += '// Canonical source SHA-256: ' + crypto.createHash('sha256').update(await readFile(entry)).digest('hex') + '\n';
header += '#ifndef XSUITE_TEMPLATES_H\n#define XSUITE_TEMPLATES_H\n';
header += 'typedef struct { const char *label; const unsigned char *data[4]; unsigned short len[4]; unsigned char tpl, time_at[4], lat_at[4], lon_at[4], text_at[4], text_wide, qty_at[4], pri_at[4], requires_fix; } xsuite_template_t;\n';
const rows = [], fixtures = [];
for (let index = 0; index < actions.length; index++) {
  const [name, label, tpl, encode, needs] = actions[index];
  const slots = [];
  for (let loc = 0; loc < 4; loc++) {
    const positioned = !!(loc & 1), editing = loc >= 2;
    if (!positioned && needs) { slots.push(null); continue; }
    const values = { t: minutes * 60000, ...(positioned ? { lat: 1.23456, lon: 2.34567 } : {}),
      ...(editing ? { note: 'XSUITE_EDIT_SLOT', text: 'XSUITE_EDIT_SLOT', qty: 0x1234, count: 0x1234, pri: 2 } : {}) };
    const bytes = Buffer.from(encode(values), 'base64url');
    const at = n => { const i = bytes.indexOf(be(n)); if (i < 0) throw Error(name + ' missing slot ' + n); return i; };
    const qtyAt = editing ? bytes.indexOf(Buffer.from([0x12, 0x34])) : -1;
    const comparePriority = editing ? Buffer.from(encode({ ...values, pri: 1 }), 'base64url') : bytes;
    const priorityAt = editing ? bytes.findIndex((b, i) => b !== comparePriority[i]) : -1;
    const slot = { time: at(minutes), lat: positioned && tpl !== 13 ? at(123456) : 255, lon: positioned && tpl !== 13 ? at(234567) : 255,
      text: editing ? bytes.indexOf(Buffer.from('XSUITE_EDIT_SLOT')) : -1, qty: qtyAt, pri: priorityAt, bytes };
    slots.push(slot);
    header += `static const unsigned char xs_${index}_${loc}[] = {${[...bytes].join(',')}};\n`;
    fixtures.push({ action: index, name, label, loc: positioned, editing, template: tpl, t: values.t, lat: values.lat, lon: values.lon, payload: bytes.toString('base64url') });
  }
  rows.push(`{${JSON.stringify(label)},{${slots.map((s, i) => s ? 'xs_' + index + '_' + i : '0').join(',')}},{${slots.map(s => s?.bytes.length || 0).join(',')}},${tpl},{${slots.map(s => s?.time ?? 255).join(',')}},{${slots.map(s => s?.lat ?? 255).join(',')}},{${slots.map(s => s?.lon ?? 255).join(',')}},{${slots.map(s => s && s.text >= 0 ? s.text : 255).join(',')}},${tpl === 13 ? 2 : 1},{${slots.map(s => s && s.qty >= 0 ? s.qty : 255).join(',')}},{${slots.map(s => s && s.pri >= 0 ? s.pri : 255).join(',')}},${needs ? 1 : 0}}`);
  if ([7, 8, 9, 17].includes(index)) for (const loc of [false, true]) for (const note of ['A', 'Field report '.repeat(5).slice(0, 64).padEnd(64, 'X')]) {
    const values = { t: minutes * 60000, ...(loc ? { lat: 1.23456, lon: 2.34567 } : {}), note, text: note, qty: 42, count: 42, pri: 0 };
    fixtures.push({ action: index, name, label, loc, editing: true, note, qty: 42, pri: 0, template: tpl, t: values.t, lat: values.lat, lon: values.lon, payload: encode(values) });
  }
}
header += 'static const xsuite_template_t xsuite_templates[] = {\n' + rows.join(',\n') + '\n};\n';
header += '#define XSUITE_ACTION_COUNT ' + actions.length + 'u\n#endif\n';
const target = path.join(root, 'core/xsuite/xsuite_templates.h');
const fixtureTarget = path.join(root, 'tests/host/xsuite-fixtures.json');
const multipartTarget = path.join(root, 'tests/host/xsuite-multipart.h');
const commandText = 'Proceed to checkpoint BRAVO. '.repeat(36).trim();
const command = 'X1.13.C.BASECOMMAND.1/1.' + p.encodeMessageClear({ ...base, prec: 'R', msgType: 0, text: commandText });
const ackId = '8765432100000002';
const ack = text => 'X1.13.C.TOCRECEIPT.1/1.' + p.encodeMessageClear({ ...base, src: 82, dst: 42, prec: 'R', msgType: 0, subject: 'ACK', text });
const multipart = '// SPDX-License-Identifier: MIT\n// Generated by the existing XTOC MESSAGE encoder.\nstatic const char xsuite_command[] = ' + JSON.stringify(command) + ';\nstatic const char xsuite_command_text[] = ' + JSON.stringify(commandText) + ';\n' +
  'static const char xsuite_ack_id[] = ' + JSON.stringify(ackId) + ';\nstatic const char xsuite_ack[] = ' + JSON.stringify(ack(ackId)) + ';\n' +
  'static const char xsuite_old_ack[] = ' + JSON.stringify(ack('8765432100000001')) + ';\n' +
  'static const char xsuite_readable_ack[] = ' + JSON.stringify(ack('Proceed to BRAVO')) + ';\n';
if (check) {
  if (await readFile(target, 'utf8') !== header) throw Error('Regenerate X Suite templates from canonical XTOC encoders');
  if (await readFile(fixtureTarget, 'utf8') !== JSON.stringify(fixtures, null, 2) + '\n') throw Error('Regenerate canonical fixtures');
  if (await readFile(multipartTarget, 'utf8') !== multipart) throw Error('Regenerate native multipart fixture');
} else {
  await writeFile(target, header);
  await writeFile(fixtureTarget, JSON.stringify(fixtures, null, 2) + '\n');
  await writeFile(multipartTarget, multipart);
}
console.log('X Suite templates: ' + actions.length + ' actions, ' + fixtures.length + ' canonical encoder fixtures');
